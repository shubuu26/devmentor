"""API route definitions for DevMentor."""

from __future__ import annotations

from fastapi import APIRouter, HTTPException
from fastapi.responses import StreamingResponse

from devmentor.agent.core import AnalysisRequest, AnalysisResponse
from devmentor.api.deps import AgentDep
from devmentor import __version__

router = APIRouter()


# ── Health & info ──────────────────────────────────────────────────────────────

@router.get("/health", tags=["system"], summary="Health check")
async def health(agent: AgentDep) -> dict:
    """Returns the status of the underlying LLM backend."""
    return await agent.health()


@router.get("/", tags=["system"], summary="API info")
async def root() -> dict:
    return {
        "name": "DevMentor API",
        "version": __version__,
        "description": "Open-source AI coding assistant powered by open-weight LLMs",
        "docs": "/docs",
        "modes": ["review", "explain", "debug", "improve", "security", "complexity", "generate"],
    }


# ── Core analysis ──────────────────────────────────────────────────────────────

@router.post(
    "/api/v1/analyze",
    response_model=AnalysisResponse,
    tags=["analysis"],
    summary="Analyse code (blocking)",
)
async def analyze(request: AnalysisRequest, agent: AgentDep) -> AnalysisResponse:
    """Submit code for analysis and receive a complete response.

    Blocks until the model finishes generating. For large snippets or slow
    machines, use the `/api/v1/analyze/stream` endpoint instead.
    """
    try:
        return await agent.analyze(request)
    except Exception as exc:
        raise HTTPException(status_code=500, detail=str(exc)) from exc


@router.post(
    "/api/v1/analyze/stream",
    tags=["analysis"],
    summary="Analyse code (streaming)",
    response_class=StreamingResponse,
)
async def analyze_stream(request: AnalysisRequest, agent: AgentDep) -> StreamingResponse:
    """Stream tokens as they are generated by the model.

    Returns a `text/event-stream` response suitable for SSE clients or
    direct terminal consumption.
    """
    async def token_generator():
        try:
            async for token in agent.stream_analyze(request):
                yield token
        except Exception as exc:
            yield f"\n\n[ERROR: {exc}]"

    return StreamingResponse(token_generator(), media_type="text/plain")


# ── Convenience shortcuts ──────────────────────────────────────────────────────

@router.post("/api/v1/review", response_model=AnalysisResponse, tags=["shortcuts"])
async def review(code: str, language: str = "python", agent: AgentDep = None) -> AnalysisResponse:
    """Quick code review via query params (for simple curl calls)."""
    return await agent.analyze(AnalysisRequest(mode="review", code=code, language=language))


@router.post("/api/v1/debug", response_model=AnalysisResponse, tags=["shortcuts"])
async def debug(code: str, question: str = "", language: str = "python", agent: AgentDep = None) -> AnalysisResponse:
    """Quick debug via query params."""
    return await agent.analyze(AnalysisRequest(mode="debug", code=code, language=language, question=question))
